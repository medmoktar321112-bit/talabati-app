-- Authenticated users receive a profile row automatically. Nobody can choose their own role.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'user' check (role in ('user', 'owner')),
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 100),
  category text not null default 'أخرى',
  price numeric(12,2) not null check (price >= 0),
  currency text not null default 'MRU',
  description text not null default '',
  image_url text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.products enable row level security;

-- Helper function reads owner role without recursive profile policies.
create or replace function public.is_owner()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'owner'
  );
$$;

revoke all on function public.is_owner() from public;
grant execute on function public.is_owner() to authenticated;

drop policy if exists "Profiles readable by self or owner" on public.profiles;
create policy "Profiles readable by self or owner"
on public.profiles for select to authenticated
using (id = auth.uid() or public.is_owner());

drop policy if exists "Users update own non-role profile fields" on public.profiles;
-- No client-side profile updates are allowed by default; edit profile fields through a trusted backend if needed.

drop policy if exists "Products are publicly readable" on public.products;
create policy "Products are publicly readable"
on public.products for select to anon, authenticated using (true);

drop policy if exists "Only owner can add products" on public.products;
create policy "Only owner can add products"
on public.products for insert to authenticated
with check (public.is_owner() and created_by = auth.uid());

drop policy if exists "Only owner can update products" on public.products;
create policy "Only owner can update products"
on public.products for update to authenticated
using (public.is_owner()) with check (public.is_owner());

drop policy if exists "Only owner can delete products" on public.products;
create policy "Only owner can delete products"
on public.products for delete to authenticated
using (public.is_owner());

-- Create a profile whenever a new Auth user signs up.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, role)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name', ''), 'user')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

